"""Compile random Cython sources with genuinely owned interpreter state.

Cython 3.3.1's module state covers Python caches, but not cdef variables,
cimport function/variable pointers or extension-class vtables. Move those
native fields into the same GC-visible module allocation. Require validated
generator landmarks instead of silently accepting a different Cython output.
"""
from pathlib import Path
import json
import re
import subprocess
import sys


def once(text, old, new):
    if text.count(old) != 1:
        raise RuntimeError(f'Cython ownership landmark mismatch: {old[:100]!r}')
    return text.replace(old, new)


def own_state(text):
    if 'Generated by Cython 3.3.1' not in text:
        raise RuntimeError('Cython ownership adapter requires exactly 3.3.1')
    if '__pyx_memoryview_obj' in text:
        raise RuntimeError('Typed memoryview runtime is not interpreter-safe')
    # An unrelated Cython extension must not donate an unprepared shared type
    # whose methods use that extension's process-global caches (or vice versa).
    text = once(text, '#define __PYX_ABI_MODULE_NAME "_cython_" CYTHON_ABI',
                '#define __PYX_ABI_MODULE_NAME "_cython_numpy_owned_v1_" CYTHON_ABI')
    # CPython type_traverse omits the metaclass edge. This metaclass is a heap
    # object owning its creating extension, so the omitted edge prevents the
    # whole native NumPy context from being reclaimed after child.close().
    metaclass_traverse = '''
static int npy_random_shared_metaclass_traverse(PyObject *type, visitproc visit, void *arg) {
    if (PyType_GetFlags(Py_TYPE(type)) & Py_TPFLAGS_HEAPTYPE) {
        Py_VISIT(Py_TYPE(type));
    }
    return PyType_Type.tp_traverse(type, visit, arg);
}
'''
    shared_metaclass = '#define __Pyx_CommonTypesMetaclass_USED' in text
    if shared_metaclass:
        text = once(text, 'static PyType_Slot __pyx_CommonTypesMetaclass_slots[] = {',
                    metaclass_traverse + 'static PyType_Slot __pyx_CommonTypesMetaclass_slots[] = {\n'
                    '    {Py_tp_traverse, (void *)npy_random_shared_metaclass_traverse},')
        text = once(text, '    Py_TPFLAGS_DEFAULT,\n    __pyx_CommonTypesMetaclass_slots',
                    '    Py_TPFLAGS_DEFAULT | Py_TPFLAGS_HAVE_GC,\n    __pyx_CommonTypesMetaclass_slots')
    elif '__pyx_CommonTypesMetaclass_slots' in text:
        raise RuntimeError('Unexpected unmarked shared Cython metaclass')
    fields = []
    aliases = []
    has_assertions = '  static int __pyx_assertions_enabled_flag;' in text
    if has_assertions:
        text = once(text, '  static int __pyx_assertions_enabled_flag;',
                    '  /* assertion mode is owned by each interpreter module */')
    fields.append('  int __pyx_assertions_enabled_flag;')
    aliases.append('#define __pyx_assertions_enabled_flag (npy_random_current_state()->__pyx_assertions_enabled_flag)')

    def native_field(match):
        declaration = match[0]
        name = re.search(r'__pyx_(?:vp_|v_|vtabptr_|vtable_)\w+|__pyx_f_\w+', declaration)[0]
        field = declaration.removeprefix('static ').split(';', 1)[0]
        field = re.sub(r'\s*=\s*0$', '', field)
        if 'PyObject' in field and '(*' not in field:
            raise RuntimeError(f'Unaccounted Python owning field: {field}')
        fields.append('  ' + field + ';')
        aliases.append(f'#define {name} (npy_random_current_state()->{name})')
        return f'/* owned native module field: {name} */'

    text = re.sub(
        r'^static (?:[^\n;()]*\b__pyx_(?:vp_|v_|vtabptr_|vtable_)\w+(?:\s*=\s*0)?|[^\n;()]*\(\*__pyx_f_\w+\)[^\n;]*);[^\n]*$',
        native_field, text, flags=re.M)
    # The assertion initializer occurs before the module allocation typedef.
    # An early getter declaration permits that field to remain truly owned.
    if has_assertions:
        text = once(text, '  #define __pyx_assertions_enabled() (__pyx_assertions_enabled_flag)',
                    '  static int *npy_random_assertion_mode(void);\n'
                    '  #define __pyx_assertions_enabled_flag (*npy_random_assertion_mode())\n'
                    '  #define __pyx_assertions_enabled() (__pyx_assertions_enabled_flag)')
    aliases = [a for a in aliases if not a.startswith('#define __pyx_assertions_enabled_flag')]
    # Normal static function declarations contain __pyx_v_self in parameters;
    # require that no function prototype was mistaken for a native variable.
    if any('/*proto*/' in f or '__pyx_v_self' in f for f in fields):
        raise RuntimeError('A function prototype matched native state extraction')
    text = once(text, '/* #### Code section: module_state_end ### */',
                '#undef __pyx_assertions_enabled_flag\n' +
                '  NPY_SI_Context npy_context;\n  int npy_runtime_version;\n' +
                '\n'.join(fields) + '\n/* #### Code section: module_state_end ### */')
    accessors = '''
static void *npy_random_attached_module_state(void) {
    return __pyx_mstate_global;
}
static __pyx_mstatetype *npy_random_current_state(void) {
    if (PyThreadState_GetUnchecked() == NULL && npy_random_detached_state != NULL) {
        return (__pyx_mstatetype *)npy_random_detached_state;
    }
    return __pyx_mstate_global;
}
static NPY_SI_Context *npy_random_module_context(void) {
    return &npy_random_current_state()->npy_context;
}
static int *npy_random_module_runtime_version(void) {
    return &npy_random_current_state()->npy_runtime_version;
}
static int *npy_random_assertion_mode(void) {
    return &npy_random_current_state()->__pyx_assertions_enabled_flag;
}
#define __pyx_assertions_enabled_flag (*npy_random_assertion_mode())
'''
    text = once(text, '/* #### Code section: module_state_clear ### */',
                accessors + '\n'.join(aliases) + '\n' +
                '\n/* #### Code section: module_state_clear ### */')
    late_deallocations = []

    def own_deallocation(match):
        body=match['body']
        # This adapter explicitly compiles without Cython object freelists.
        # Prune only those inactive branches before auditing late type access.
        live_lines=[]
        skipped_depth=0
        for line in body.splitlines(keepends=True):
            directive=line.strip()
            if skipped_depth:
                if re.match(r'#\s*if(?:def|ndef)?\b', directive): skipped_depth+=1
                elif re.match(r'#\s*endif\b', directive): skipped_depth-=1
                continue
            if directive=='#if CYTHON_USE_FREELISTS':
                skipped_depth=1
            else:
                live_lines.append(line)
        if skipped_depth: raise RuntimeError('Unbalanced Cython freelist conditional')
        body=''.join(live_lines)
        cached_bases=set(re.findall(r'__pyx_mstate_global->__pyx_ptype_\w+', body))
        if not cached_bases:
            return 'static void __pyx_tp_dealloc_'+match['name']+'(PyObject *o) {'+body+'}'
        if len(cached_bases)!=1:
            raise RuntimeError('Multiple native bases in one Cython deallocator')
        base,=cached_bases
        if not base.endswith('_BitGenerator'):
            raise RuntimeError(f'Unreviewed late-deallocation base: {base}')
        function='__pyx_tp_dealloc_'+match['name']
        body=body.replace(base,'npy_native_base')
        body=body.replace('__Pyx_PyType_HasFeature(npy_native_base, Py_TPFLAGS_HEAPTYPE)',
                          'npy_native_base_is_heap')
        body=('\n  PyTypeObject *npy_native_base = npy_random_next_dealloc_base(o, '+function+');\n'
              '  const int npy_native_base_is_heap = (PyType_GetFlags(npy_native_base) & Py_TPFLAGS_HEAPTYPE) != 0;\n'+body)
        late_deallocations.append(function)
        return 'static void '+function+'(PyObject *o) {'+body+'}'

    text=re.sub(r'^static void __pyx_tp_dealloc_(?P<name>\w+)\(PyObject \*o\) \{(?P<body>.*?)^}',
                own_deallocation,text,flags=re.M|re.S)
    text = once(text, '/* #### Code section: module_state ### */',
                '#if !CYTHON_USE_MODULE_STATE || !CYTHON_USE_TYPE_SPECS || CYTHON_USE_FREELISTS\n'
                '#error "Owned random modules require module state, heap types, and no object freelists"\n'
                '#endif\n/* #### Code section: module_state ### */')
    text = once(text, '/* #### Code section: module_state_clear_end ### */',
                'NPY_SI_Context_Clear(&clear_module_state->npy_context);\n'
                '/* #### Code section: module_state_clear_end ### */')
    text = once(text, '/* #### Code section: module_state_traverse_end ### */',
                'if (NPY_SI_Context_Traverse(&traverse_module_state->npy_context, visit, arg) < 0) return -1;\n'
                '/* #### Code section: module_state_traverse_end ### */')
    # The Cython registry borrows modules. The exec argument already owns the
    # module; transferring another INCREF to that borrowed entry leaks it.
    text, transfers = re.subn(
        r'(__pyx_t_1 = 0; /\* transfer ownership from __pyx_t_1 to "[^\n]+)',
        r'Py_DECREF(__pyx_t_1); /* registry borrows the exec module */\n    \1', text)
    if transfers != 1:
        raise RuntimeError(f'Cython exec reference transfer count: {transfers}')
    text = once(text, '    Py_DECREF(__pyx_m);\n    if (pystate_addmodule_run)',
                '    /* exec module was borrowed; no transferred reference */\n    if (pystate_addmodule_run)')
    # Clear may follow failed exec, which has already removed the entry.
    text = once(text, '  __Pyx_State_RemoveModule(NULL);\n',
                '  if (__Pyx_State_FindModule(&__pyx_moduledef) == m) __Pyx_State_RemoveModule(NULL);\n')
    # Keep the existing per-region saved threadstate and restore paths; a
    # parallel local preserves the previous borrowed owner under reentry.
    text, declarations = re.subn(r'PyThreadState\s*\*\s*_save;',
                               'PyThreadState *_save; npy_random_detached_scope _npy_previous_owner;', text)
    text, saves = re.subn(r'_save = PyEval_SaveThread\(\);',
                         '_save = npy_random_save_thread(&_npy_previous_owner);', text)
    text, restores = re.subn(r'PyEval_RestoreThread\(_save\);',
                            'npy_random_restore_thread(_save, _npy_previous_owner);', text)
    if saves != declarations or (saves and restores < saves):
        raise RuntimeError(f'Cython detached scope mismatch: {declarations}/{saves}/{restores}')
    runtime = Path(__file__).with_name('_cython_si_runtime.h').read_text()
    text = once(text, '#include "Python.h"', '#include "Python.h"\n' + runtime)
    return text, {'native_fields': fields, 'detach_scopes': saves, 'restore_paths': restores,
                  'shared_metaclass_GC_edge': shared_metaclass,
                  'late_deallocation_actual_base': late_deallocations}


def main():
    source, output, name, source_root, build_root = sys.argv[1:]
    argv = [sys.executable, '-m', 'cython', '--fast-fail', '-3',
            '-Xfreethreading_compatible=True', '-Xsubinterpreters_compatible=own_gil',
            '--module-name', 'numpy.random.' + name,
            '-I', build_root, '-I', source_root, '-o', output, source]
    subprocess.run(argv, check=True)
    text, record = own_state(Path(output).read_text())
    Path(output).write_text(text)
    Path(output + '.ownership.json').write_text(json.dumps(record, indent=2) + '\n')


if __name__ == '__main__':
    main()
